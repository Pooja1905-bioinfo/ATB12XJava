package ATBX_Tasks.If_else;

public class Task007_Smallest_of_two {
    public static void main(String[] args) {
        int n1 = 7;
        int  n2 = 54;
        if(n1 < n2){
            System.out.println(n1 +" is the smaller than " + n2);
        }
        else{
            System.out.println(n2 +" is the smaller than " + n1);
        }
    }
}
