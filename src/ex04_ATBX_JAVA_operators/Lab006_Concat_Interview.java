package ex04_ATBX_JAVA_operators;

public class Lab006_Concat_Interview {
    public static void main(String[] args) {
        String a = "Pooja";
        String b = " Gaydhani";
        System.out.println(a+b);   // + -> concat ( string)

        int p = 10;
        int q = 20;
        System.out.println(p+q);  // + -> addition (integer)
        // Operator overloading -> same operator behaving differently in diff data type
    }
}
