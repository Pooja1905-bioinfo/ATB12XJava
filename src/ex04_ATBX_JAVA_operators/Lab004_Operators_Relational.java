package ex04_ATBX_JAVA_operators;

public class Lab004_Operators_Relational {
    public static void main(String[] args) {
        //  < less than
        // < = less than equal to
        // > greater than
        // > = greater than equal to
        // == equal to
        // != not equal to

        // result always boolean true/false
        int a = 30;
        int b = 40;
        System.out.println( a==b);
        System.out.println( a < b);
        System.out.println( a<=b);
        System.out.println( a>=b);
        System.out.println( a!=b);
        System.out.println( a > b);
    }
}
