package ex04_ATBX_JAVA_operators;

public class Lab012_All_Operators {
    public static void main(String[] args) {
        int a = 10;
        int b = 30;
        System.out.println(a+b);
        System.out.println(a==b);
        System.out.println(a>b);
        System.out.println(a!=b);
        System.out.println(a< b);
        System.out.println(a<=b);
    }
}
